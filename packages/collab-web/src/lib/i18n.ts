function storedLanguage(): Language {
	try {
		return globalThis.localStorage.getItem(STORAGE_KEY) === "es" ? "es" : "en";
	} catch {
		return "en";
	}
}

// This shared module is also checked by the CLI without the full DOM library.
declare const document:
	| {
			querySelector(selector: string): { getAttribute(name: string): string | null } | null;
			documentElement: { lang: string };
	  }
	| undefined;

const exportLocale =
	typeof document === "undefined"
		? undefined
		: document.querySelector('meta[name="omp-export-locale"]')?.getAttribute("content");
let language: Language = exportLocale === "en" || exportLocale === "es" ? exportLocale : storedLanguage();
const listeners = new Set<() => void>();

function applyLanguage(): void {
	if (typeof document !== "undefined") document.documentElement.lang = language;
}
applyLanguage();

export function setLanguage(next: Language): void {
	language = next;
	try {
		globalThis.localStorage.setItem(STORAGE_KEY, next);
	} catch {
		// The in-memory choice still works when storage is unavailable.
	}
	applyLanguage();
	for (const listener of listeners) listener();
}

function subscribe(listener: () => void): () => void {
	listeners.add(listener);
	return () => listeners.delete(listener);
}

export function useLanguage(): Language {
	return useSyncExternalStore(
		subscribe,
		() => language,
		() => "en",
	);
}
export type Translation = (key: string, english: string, values?: Readonly<Record<string, string | number>>) => string;

export function interpolate(message: string, values: Readonly<Record<string, string | number>> | undefined): string {
	if (!values) return message;
	return message.replace(/\{([a-zA-Z0-9_]+)\}/g, (placeholder, key: string) =>
		Object.hasOwn(values, key) ? String(values[key]) : placeholder,
	);
}

export function useTranslation(): Translation {
	const current = useLanguage();
	return (key, english, values) => interpolate(current === "es" ? (spanish[key] ?? english) : english, values);
}

export function LocalizedText({ messageKey, english }: { messageKey: string; english: string }): string {
	return useTranslation()(messageKey, english);
}
