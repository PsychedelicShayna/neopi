/* A translated page carries its texts in an inert JSON block (<script type="application/json" id="editor-i18n">);
   whatever it holds replaces the English above, key by key. */
Object.assign(STRINGS, JSON.parse(document.getElementById("editor-i18n")?.textContent || "{}"));
const TAGS = { b: ["b"], j: ["span", "j"], c: ["code"], k: ["kbd"], i: ["i"], s: ["s"], w: ["span", "unk"] };
const TOKEN = /\{(\w+)\}|<(\/?)([bjckisw])>/g;
const lookup = key => STRINGS[key] ?? key;
const plainText = (source, vars) =>
	source.replace(TOKEN, (_, name) => (name === undefined ? "" : String(vars?.[name] ?? "")));
function richText(source, vars) {
	const root = [];
	const stack = [root];
	const add = item => {
		const top = stack.at(-1);
		for (const piece of [item].flat(Infinity)) {
			if (piece === null || piece === undefined || piece === false || piece === "") continue;
			if (top === root) root.push(piece);
			else top.append(piece.nodeType ? piece : document.createTextNode(String(piece)));
		}
	};
	let at = 0;
	for (const match of source.matchAll(TOKEN)) {
		add(source.slice(at, match.index));
		at = match.index + match[0].length;
		const [, name, closing, tag] = match;
		if (name !== undefined) add(typeof vars?.[name] === "function" ? vars[name]() : vars?.[name]);
		else if (closing) {
			if (stack.length > 1) stack.pop();
		} else {
			const [element, className] = TAGS[tag];
			const el = document.createElement(element);
			if (className) el.className = className;
			add(el);
			stack.push(el);
		}
	}
	add(source.slice(at));
	return root;
}
/** Plain string: tags dropped, vars stringified. For titles, labels, placeholders, toasts. */
const T = (key, vars) => plainText(lookup(key), vars);
/** `key.one` when n is 1, otherwise `key.other`; `{n}` is available in both. */
const TN = (key, n, vars) => T(key + (n === 1 ? ".one" : ".other"), { n, ...vars });
/** DOM nodes and strings, with tags turned into elements. Vars may be nodes, or functions that make one
 * (needed when a placeholder appears more than once). For anything built with h(). */
const TX = (key, vars) => richText(lookup(key), vars);
