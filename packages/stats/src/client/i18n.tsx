const LocaleContext = createContext<Locale>("en");

/** A controlled locale for an embedded trace; does not touch the host document or network. */
export function TraceLocaleScope({ locale, children }: { locale: Locale; children: ReactNode }) {
	return <LocaleContext.Provider value={locale}>{children}</LocaleContext.Provider>;
}

/** A launch URL can select a locale independently of a reused dashboard server. */
export function LocaleProvider({ children }: { children: ReactNode }) {
	const explicit = isHostedDashboard() ? null : new URLSearchParams(window.location.search).get("lang");
	const [locale, setLocale] = useState<Locale>(explicit === "es" ? "es" : "en");
	useEffect(() => {
		if (explicit === "en" || explicit === "es") return;
		const controller = new AbortController();
		statsFetch("/api/locale", { signal: controller.signal })
			.then(response => (response.ok ? response.json() : null))
			.then((value: unknown) => {
				if (
					!controller.signal.aborted &&
					typeof value === "object" &&
					value !== null &&
					"locale" in value &&
					value.locale === "es"
				)
					setLocale("es");
			})
			.catch(() => {});
		return () => controller.abort();
	}, [explicit]);
	useEffect(() => {
		document.documentElement.lang = locale;
	}, [locale]);
	return <LocaleContext.Provider value={locale}>{children}</LocaleContext.Provider>;
}

function interpolate(message: string, values: Readonly<Record<string, string | number>> | undefined): string {
	if (!values) return message;
	return message.replace(/\{([a-zA-Z0-9_]+)\}/g, (placeholder, key: string) =>
		Object.hasOwn(values, key) ? String(values[key]) : placeholder,
	);
}

export function useLocale(): Locale {
	return useContext(LocaleContext);
}

/** English stays the source and fallback for untranslated or review-pending copy. */
export function useTranslation(): Translation {
	const locale = useLocale();
	return useCallback<Translation>(
		(key, english, values) => interpolate(locale === "es" ? (spanish[key] ?? english) : english, values),
		[locale],
	);
}

export function LocalizedText({ messageKey, english }: { messageKey: string; english: string }): string {
	return useTranslation()(messageKey, english);
}
